const out: CoreIdentity[] = []
for (const [owner, rows] of Object.entries(OWNED) as [AgentId, Row[]][]) {
  for (const [id, name, iast, deva, aliases] of rows) {
    const prefix = id.split(':')[0]
    const rec: CoreIdentity = { id, type: TYPE_OF[prefix], name, owner }
    if (iast) rec.iast = iast
    if (deva) rec.devanagari = deva
    if (aliases) rec.aliases = aliases.split('|')
    out.push(rec)
  }
}
const ids = new Set<string>()
for (const r of out) {
  if (ids.has(r.id)) throw new Error(`duplicate core id ${r.id}`)
  if (!r.type) throw new Error(`unknown prefix for ${r.id}`)
  ids.add(r.id)
}
writeFileSync(join(import.meta.dirname, '..', 'data', 'core-registry.json'), JSON.stringify(out, null, 1) + '\n')
console.log(`core registry: ${out.length} identities`)
