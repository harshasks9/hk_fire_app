/* ---------------------------------------------------------------- Avatar */
export function Avatar({ name, size = 24, className }: { name: string; size?: number; className?: string }) {
  const initials = name.split(/\s+/).filter(Boolean).slice(0, 2).map((p) => p[0]!.toUpperCase()).join('')
  const hue = [...name].reduce((h, c) => (h * 31 + c.charCodeAt(0)) % 360, 7)
  return (
    <span className={cx('inline-flex shrink-0 items-center justify-center rounded-full font-semibold text-white', className)} style={{ width: size, height: size, fontSize: Math.max(9, size * 0.4), background: `oklch(0.55 0.09 ${hue})` }} aria-hidden>
      {initials}
    </span>
  )
}

