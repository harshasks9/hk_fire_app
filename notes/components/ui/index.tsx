/* ---------------------------------------------------------------- Popover (hover / click) */
export function Popover({ trigger, children, align = 'start', className, openOn = 'hover' }: { trigger: React.ReactNode; children: React.ReactNode; align?: 'start' | 'end' | 'center'; className?: string; openOn?: 'hover' | 'click' }) {
  const [open, setOpen] = React.useState(false)
  const ref = React.useRef<HTMLDivElement>(null)
  const timer = React.useRef<number | undefined>(undefined)
  React.useEffect(() => {
    if (!open || openOn !== 'click') return
    const onDoc = (e: MouseEvent) => {
      if (!ref.current?.contains(e.target as Node)) setOpen(false)
    }
    document.addEventListener('mousedown', onDoc)
    return () => document.removeEventListener('mousedown', onDoc)
  }, [open, openOn])
  const hoverProps = openOn === 'hover' ? {
    onMouseEnter: () => { window.clearTimeout(timer.current); timer.current = window.setTimeout(() => setOpen(true), 180) },
    onMouseLeave: () => { window.clearTimeout(timer.current); timer.current = window.setTimeout(() => setOpen(false), 120) },
  } : { onClick: () => setOpen((o) => !o) }
  return (
    <div ref={ref} className="relative inline-flex" {...hoverProps}>
      {trigger}
      {open ? (
        <div className={cx('animate-pop absolute top-full z-40 mt-1.5 rounded-xl border border-border bg-surface p-3 shadow-pop', align === 'end' ? 'right-0' : align === 'center' ? 'left-1/2 -translate-x-1/2' : 'left-0', className)} onClick={(e) => e.stopPropagation()}>
          {children}
        </div>
      ) : null}
    </div>
  )
}

/* ---------------------------------------------------------------- Menu */
export function Menu({ trigger, items, align = 'end' }: { trigger: React.ReactNode; items: { label: string; onSelect?: () => void; href?: string; danger?: boolean; icon?: React.ReactNode; disabled?: boolean }[]; align?: 'start' | 'end' }) {
  const [open, setOpen] = React.useState(false)
  const ref = React.useRef<HTMLDivElement>(null)
  React.useEffect(() => {
    if (!open) return
    const onDoc = (e: MouseEvent) => { if (!ref.current?.contains(e.target as Node)) setOpen(false) }
    const onKey = (e: KeyboardEvent) => { if (e.key === 'Escape') setOpen(false) }
    document.addEventListener('mousedown', onDoc)
    document.addEventListener('keydown', onKey)
    return () => { document.removeEventListener('mousedown', onDoc); document.removeEventListener('keydown', onKey) }
  }, [open])
  return (
    <div ref={ref} className="relative inline-flex">
      <span onClick={() => setOpen((o) => !o)}>{trigger}</span>
      {open ? (
        <div className={cx('animate-pop absolute top-full z-40 mt-1 min-w-[180px] rounded-xl border border-border bg-surface p-1 shadow-pop', align === 'end' ? 'right-0' : 'left-0')} role="menu">
          {items.map((it, i) =>
            it.href ? (
              <Link key={i} href={it.href} className="flex items-center gap-2 rounded-lg px-2.5 py-1.5 text-[13.5px] hover:bg-surface-2" onClick={() => setOpen(false)} role="menuitem">
                {it.icon}{it.label}
              </Link>
            ) : (
              <button key={i} disabled={it.disabled} className={cx('flex w-full items-center gap-2 rounded-lg px-2.5 py-1.5 text-left text-[13.5px] hover:bg-surface-2 disabled:opacity-50', it.danger && 'text-danger')} onClick={() => { setOpen(false); it.onSelect?.() }} role="menuitem">
                {it.icon}{it.label}
              </button>
            ),
          )}
        </div>
      ) : null}
    </div>
  )
}

/* ---------------------------------------------------------------- Toast */
type Toast = { id: number; text: string; tone?: 'neutral' | 'success' | 'danger' }
const ToastCtx = React.createContext<{ push: (t: Omit<Toast, 'id'>) => void } | null>(null)
export function ToastProvider({ children }: { children: React.ReactNode }) {
  const [toasts, setToasts] = React.useState<Toast[]>([])
  const push = React.useCallback((t: Omit<Toast, 'id'>) => {
    const id = Date.now() + Math.random()
    setToasts((ts) => [...ts, { ...t, id }])
    window.setTimeout(() => setToasts((ts) => ts.filter((x) => x.id !== id)), 2600)
  }, [])
  return (
    <ToastCtx.Provider value={{ push }}>
      {children}
      <div className="pointer-events-none fixed bottom-20 left-1/2 z-[100] flex -translate-x-1/2 flex-col items-center gap-2 md:bottom-6">
        {toasts.map((t) => (
          <div key={t.id} className={cx('animate-up rounded-lg border border-border bg-surface px-3 py-2 text-[13px] shadow-pop', t.tone === 'success' && 'text-success', t.tone === 'danger' && 'text-danger')}>{t.text}</div>
        ))}
      </div>
    </ToastCtx.Provider>
  )
}
export function useToast() {
  const ctx = React.useContext(ToastCtx)
  return ctx ?? { push: () => undefined }
}

/* ---------------------------------------------------------------- Copy button */
export function CopyButton({ text, label = 'Copy' }: { text: string; label?: string }) {
  const [done, setDone] = React.useState(false)
  return (
    <Button size="sm" variant="ghost" onClick={async () => { try { await navigator.clipboard.writeText(text); setDone(true); setTimeout(() => setDone(false), 1500) } catch { /* ignore */ } }}>
      {done ? 'Copied' : label}
    </Button>
  )
}

/* ---------------------------------------------------------------- Simple markdown renderer (for AI outputs) */
export function Markdown({ text, className }: { text: string; className?: string }) {
  const html = React.useMemo(() => renderMarkdown(text), [text])
  return <div className={cx('prose-static text-[14px] leading-relaxed [&_mark]:rounded [&_mark]:bg-warning/25 [&_mark]:px-0.5 [&_table]:my-2 [&_table]:w-full [&_table]:text-[13px] [&_td]:border [&_td]:border-border [&_td]:px-2 [&_td]:py-1 [&_th]:border [&_th]:border-border [&_th]:bg-surface-2 [&_th]:px-2 [&_th]:py-1 [&_th]:text-left [&_a]:text-accent [&_a]:underline', className)} dangerouslySetInnerHTML={{ __html: html }} />
}

function esc(s: string) {
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
}
function inlineMd(s: string) {
  return esc(s)
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^*])\*([^*\n]+)\*/g, '$1<em>$2</em>')
    .replace(/_([^_\n]+)_/g, '<em>$1</em>')
    .replace(/`([^`]+)`/g, '<code>$1</code>')
    .replace(/\[(\d+)\]/g, '<a href="#cite-$1" data-cite="$1" class="cite">[$1]</a>')
    .replace(/\[([^\]]+)\]\((https?:[^)]+)\)/g, '<a href="$2" target="_blank" rel="noreferrer">$1</a>')
}
export function renderMarkdown(md: string): string {
  const lines = md.replace(/\r/g, '').split('\n')
  const out: string[] = []
  let i = 0
  while (i < lines.length) {
    const l = lines[i]!
    if (!l.trim()) { i++; continue }
    const h = l.match(/^(#{1,4})\s+(.*)$/)
    if (h) { out.push(`<h${h[1]!.length + 1} class="font-semibold mt-3 mb-1">${inlineMd(h[2]!)}</h${h[1]!.length + 1}>`); i++; continue }
    if (/^\|/.test(l)) {
      const rows: string[] = []
      while (i < lines.length && /^\|/.test(lines[i]!)) { const cells = lines[i]!.split('|').slice(1, -1).map((c) => c.trim()); if (!cells.every((c) => /^:?-+:?$/.test(c))) rows.push(cells.map((c, ci) => rows.length === 0 ? `<th>${inlineMd(c)}</th>` : `<td>${inlineMd(c)}</td>`).join('')); i++ }
      out.push(`<table>${rows.map((r) => `<tr>${r}</tr>`).join('')}</table>`); continue
    }
    if (/^\s*[-*•]\s+\[[ xX]\]\s+/.test(l)) {
      const items: string[] = []
      while (i < lines.length && /^\s*[-*•]\s+\[[ xX]\]\s+/.test(lines[i]!)) { const m = lines[i]!.match(/^\s*[-*•]\s+\[([ xX])\]\s+(.*)$/)!; items.push(`<li class="flex gap-2"><span class="mt-0.5 inline-block h-3.5 w-3.5 shrink-0 rounded border border-border-2 ${m[1] !== ' ' ? 'bg-accent' : ''}"></span><span>${inlineMd(m[2]!)}</span></li>`); i++ }
      out.push(`<ul class="my-1 space-y-1 list-none pl-0">${items.join('')}</ul>`); continue
    }
    if (/^\s*[-*•]\s+/.test(l)) {
      const items: string[] = []
      while (i < lines.length && /^\s*[-*•]\s+/.test(lines[i]!)) { items.push(`<li>${inlineMd(lines[i]!.replace(/^\s*[-*•]\s+/, ''))}</li>`); i++ }
      out.push(`<ul class="my-1 list-disc pl-5 space-y-0.5">${items.join('')}</ul>`); continue
    }
    if (/^\s*\d+[.)]\s+/.test(l)) {
      const items: string[] = []
      while (i < lines.length && /^\s*\d+[.)]\s+/.test(lines[i]!)) { items.push(`<li>${inlineMd(lines[i]!.replace(/^\s*\d+[.)]\s+/, ''))}</li>`); i++ }
      out.push(`<ol class="my-1 list-decimal pl-5 space-y-0.5">${items.join('')}</ol>`); continue
    }
    if (/^>\s?/.test(l)) { out.push(`<blockquote class="border-l-2 border-border-2 pl-3 text-fg-2">${inlineMd(l.replace(/^>\s?/, ''))}</blockquote>`); i++; continue }
    const buf: string[] = []
    while (i < lines.length && lines[i]!.trim() && !/^(#{1,4}\s|\||\s*[-*•]\s|\s*\d+[.)]\s|>)/.test(lines[i]!)) buf.push(lines[i++]!)
    out.push(`<p>${inlineMd(buf.join(' '))}</p>`)
  }
  return out.join('\n')
}
