/* ---------------------------------------------------------------- Button */
type ButtonVariant = 'primary' | 'secondary' | 'ghost' | 'danger' | 'subtle'
type ButtonSize = 'sm' | 'md' | 'lg' | 'icon'
export interface ButtonProps extends React.ButtonHTMLAttributes<HTMLButtonElement> { variant?: ButtonVariant; size?: ButtonSize; loading?: boolean }

const base = 'inline-flex items-center justify-center gap-1.5 rounded-[9px] font-medium transition-all duration-150 select-none disabled:opacity-50 disabled:pointer-events-none whitespace-nowrap'
const variants: Record<ButtonVariant, string> = {
  primary: 'bg-accent text-accent-fg hover:bg-accent-hover shadow-[0_1px_0_rgba(0,0,0,0.05)]',
  secondary: 'bg-surface text-fg border border-border-2 hover:bg-surface-2',
  ghost: 'text-fg-2 hover:text-fg hover:bg-surface-2',
  subtle: 'bg-surface-2 text-fg hover:bg-surface-3',
  danger: 'text-danger hover:bg-danger/10',
}
// Touch screens get taller targets (pointer-coarse) without changing the desktop density.
const sizes: Record<ButtonSize, string> = { sm: 'h-7 px-2.5 text-[13px] pointer-coarse:h-9 pointer-coarse:px-3', md: 'h-8 px-3 text-[13.5px] pointer-coarse:h-10', lg: 'h-10 px-4 text-[15px] pointer-coarse:h-11', icon: 'h-8 w-8 p-0 pointer-coarse:h-10 pointer-coarse:w-10' }

export const Button = React.forwardRef<HTMLButtonElement, ButtonProps>(function Button({ className, variant = 'secondary', size = 'md', loading, children, ...props }, ref) {
  return (
    <button ref={ref} className={cx(base, variants[variant], sizes[size], className)} {...props}>
      {loading ? <Spinner className="h-3.5 w-3.5" /> : null}
      {children}
    </button>
  )
})

export function Spinner({ className }: { className?: string }) {
  return (
    <svg className={cx('animate-spin', className ?? 'h-4 w-4')} viewBox="0 0 24 24" fill="none" aria-hidden>
      <circle cx="12" cy="12" r="9" stroke="currentColor" strokeWidth="2.5" opacity="0.2" />
      <path d="M21 12a9 9 0 0 0-9-9" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" />
    </svg>
  )
}

